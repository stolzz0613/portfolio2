// Renders every sprite to data URIs in sprites.js, which goes into the page as the SPRITES constant.
import fs from 'node:fs';

import { hero, CLASSES } from './heroes.mjs';
import { pet, PET_FORMS, egg, EGG_TINTS } from './pets.mjs';
import { foe, FOES } from './monsters.mjs';
import { scene, SCENES } from './scenes.mjs';
const uri = (s) => 'data:image/png;base64,' + Buffer.from(s.png()).toString('base64');
const out = { hero: {}, pet: {}, egg: {}, foe: {}, scene: {} };
for (const k of Object.keys(CLASSES)) out.hero[k] = uri(hero(CLASSES[k]));
for (const [id, st, line] of PET_FORMS) out.pet[`${id}-${st}${st >= 2 ? line : ''}`] = uri(pet(id, st, line));
for (const [k, t] of Object.entries(EGG_TINTS)) for (let c = 0; c < 4; c++) out.egg[`${k}-${c}`] = uri(egg(t, c));
for (const k of Object.keys(FOES)) out.foe[k] = uri(foe(k));
for (const k of Object.keys(SCENES)) out.scene[k] = uri(scene(k));
const js = `// Generated by sprites/pack.mjs: original pixel art, no external assets.\nconst SPRITES = ${JSON.stringify(out)};\n`;
fs.writeFileSync(new URL('./sprites.js', import.meta.url), js);
console.log('sprites.js', Math.round(js.length / 1024), 'KB;', Object.entries(out).map(([k, v]) => `${k} ${Object.keys(v).length}`).join(', '));
